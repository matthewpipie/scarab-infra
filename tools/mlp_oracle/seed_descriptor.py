#!/usr/bin/env python3
"""A study's controls drawn again with another seed, for a few workloads: how much a control's gain
depends on its random draw.

    python tools/mlp_oracle/seed_descriptor.py mlp_oracle_google_defmark --workloads sierra.a.4,whiskey --seed 1

writes json/<study>_seed<N>.json: the study's descriptor with its lru and its controls only, the controls
drawn with --mlp_oracle_seed N, for those workloads. To add workloads to a seed that has run, give the new
ones a --tag: json/<study>_seed<N>_<tag>.json is its own experiment (sci overwrites an experiment it runs
again), and plot.py takes both. It replays the study's reference (the same
--mlp_oracle_ref), so run it where that reference's records are (the host that ran it, or pakuchi once
pulled). lru stays so report.py has a baseline, and as a check: plot.py refuses a seed study whose lru
differs from the study's.
"""
import argparse
import json
import re
import sys
from pathlib import Path

INFRA = Path(__file__).resolve().parents[2]


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("study", help="the study's replay descriptor, e.g. mlp_oracle_google_defmark")
    p.add_argument("--workloads", required=True, help="comma-separated workloads of the study")
    p.add_argument("--seed", type=int, default=1, help="--mlp_oracle_seed for the controls (the study's is 0)")
    p.add_argument("--tag", default="", help="suffix for the experiment name, to add workloads to a seed that has run")
    a = p.parse_args()
    if a.seed == 0:
        sys.exit("seed 0 is the study's own draw")
    src = INFRA / "json" / f"{a.study}.json"
    d = json.loads(src.read_text())
    wls = [w.strip() for w in a.workloads.split(",") if w.strip()]
    sims = [s for s in d["simulations"] if s["workload"] in wls]
    missing = sorted(set(wls) - {s["workload"] for s in sims})
    if missing:
        sys.exit(f"{a.study} has no workload {', '.join(missing)}")
    cfgs = {"lru": d["configurations"]["lru"]}
    for name, c in d["configurations"].items():
        if re.search(r"--mlp_oracle[ =]3\b", c.get("params", "")):
            c = dict(c)
            c["params"] = re.sub(r"\s*--mlp_oracle_seed[ =]\S+", "", c["params"]) + f" --mlp_oracle_seed {a.seed}"
            c["_params"] = c.get("_params", "") + f" Drawn with --mlp_oracle_seed {a.seed} (the main study's is seed 0)."
            cfgs[f"{name}_s{a.seed}"] = c
    if len(cfgs) == 1:
        sys.exit(f"{a.study} has no control configs (--mlp_oracle 3)")
    name = f"{a.study}_seed{a.seed}" + (f"_{a.tag}" if a.tag else "")
    d["experiment"] = f"{d['experiment']}_seed{a.seed}" + (f"_{a.tag}" if a.tag else "")
    d["_experiment"] = (f"Second-seed controls for {', '.join(wls)} of {a.study}: its lru and controls, drawn with "
                        f"--mlp_oracle_seed {a.seed}. They replay the study's reference, so run them where its records "
                        "are. lru must equal the main study's. Generated by tools/mlp_oracle/seed_descriptor.py.")
    d["simulations"] = sims
    d["_simulations"] = f"{', '.join(wls)} from {a.study}, same simpoints and lengths."
    d["configurations"] = cfgs
    if isinstance(d.get("visualize"), dict):
        d["visualize"]["configs"] = list(cfgs)
    out = INFRA / "json" / f"{name}.json"
    out.write_text(json.dumps(d, indent=2, separators=(",", ":"), ensure_ascii=False) + "\n")
    print(f"wrote {out.relative_to(INFRA)}: {len(sims)} workloads, configs {', '.join(cfgs)}")


if __name__ == "__main__":
    main()
