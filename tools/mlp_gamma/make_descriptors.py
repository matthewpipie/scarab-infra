#!/usr/bin/env python3
"""Write the REPL_MLP gamma-sweep descriptors (json/mlp_gamma_<suite>_<arch>.json).

Every descriptor crosses --mlp_lin_instr_lambda with --mlp_lin_data_lambda over GAMMAS on
REPL_MLP (--mlc_cache_repl_policy 9) with fill-counted boost (--mlp_boost_in_fills 1), one
descriptor per (suite, architecture) because sci takes one architecture and one traces_dir per
descriptor. Config gi<I>_gd<D> is instruction gamma I and data gamma D; gi0_gd0 is plain LRU.

    python tools/mlp_gamma/make_descriptors.py                  # the sweep
    python tools/mlp_gamma/make_descriptors.py --check          # small smoke test
    python tools/mlp_gamma/make_descriptors.py --binary scarab_<hash>   # rerun on a new build
"""

