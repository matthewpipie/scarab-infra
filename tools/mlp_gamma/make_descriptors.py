def simulations(suite, cfg):
    sims = []
    names = cfg["workloads"] or [None]
    for wl in names:
        sims.append({
            "suite": suite,
            "subsuite": suite if wl else None,
            "workload": wl,
            "cluster_id": None,
            "simulation_type": "memtrace",
            "warmup": WARMUP,
        })
    return sims


def measured_text(cfg):
    if cfg["inst_limit"]:
        return f"{WARMUP // 10**6}M warmup + {(cfg['inst_limit'] - WARMUP) // 10**6}M measured"
    return f"{WARMUP // 10**6}M warmup + the 10M simpoint segment measured"


def grid(gammas):
    return [(gi, gd) for gi in gammas for gd in gammas]


CHECK_PAIRS = [(0, 0), (64, 0), (0, 16), (64, 16)]


def configurations(binary, inst_limit, pairs, with_lru):
    configs = {}
    limit = f" --inst_limit {inst_limit}" if inst_limit else ""
    if with_lru:
        configs["lru"] = {
            "_params": "Plain L2 LRU (policy 0), to confirm gi0_gd0 reproduces it.",
            "params": limit.strip(),
            "binary": binary,
            "slurm_options": "",
            "memory_overhead_mb": 64,
        }
    for gi, gd in pairs:
        configs[f"gi{gi}_gd{gd}"] = {
            "_params": f"REPL_MLP, fill-counted, instruction gamma {gi}, data gamma {gd}"
            + (" (plain LRU)." if gi == gd == 0 else "."),
            "params": "--mlc_cache_repl_policy 9 --mlp_boost_in_fills 1"
            f" --mlp_lin_instr_lambda {gi} --mlp_lin_data_lambda {gd}{limit}",
            "binary": binary,
            "slurm_options": "",
            "memory_overhead_mb": 64,
        }
    return configs


